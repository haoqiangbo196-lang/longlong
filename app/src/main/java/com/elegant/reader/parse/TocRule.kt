package com.elegant.reader.parse

/**
 * 章节标题识别规则（移植自 Legado 的 txtTocRule.json 默认规则）。
 *
 * 只保留 enable=true 的高置信度规则，按 Legado 的 serialNumber 顺序匹配，
 * 命中即判定为章节标题。规则覆盖：
 *   - 「第X章/节/卷/集/部/篇」标准格式
 *   - 序章/楔子/正文/终章/后记/尾声/番外等结构词
 *   - 数字 + 分隔符 + 标题（1、xxx / 一、xxx）
 *   - Chapter/Section/Part/Episode 序号
 *   - 特殊符号包裹标题（【】「」☆★ 等）
 *   - 章/卷 序号 标题
 */
object TocRule {

    /**
     * 默认启用的章节标题规则（按优先级排序）。
     */
    private val rules: List<Regex> = listOf(
        // 目录（标准「第X章」格式，允许行首空白）
        Regex("^[ 　\\t]{0,4}(?:序章|楔子|正文(?!完|结)|终章|后记|尾声|番外|第\\s{0,4}[\\d〇零一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]+?\\s{0,4}(?:章|节(?!课)|卷|集(?![合和])|部(?![分赛游])|篇(?!张))).{0,30}$"),

        // 数字 分隔符 标题名称（1、xxx / 1: xxx）
        Regex("^[ 　\\t]{0,4}\\d{1,5}[:：,.， 、_—\\-].{1,30}$"),

        // 大写数字 分隔符 标题名称（一、xxx / 二十四章 xxx）
        Regex("^[ 　\\t]{0,4}(?:序章|楔子|正文(?!完|结)|终章|后记|尾声|番外|[零一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]{1,8}章?)[ 、_—\\-].{1,30}$"),

        // 正文 标题/序号
        Regex("^[ 　\\t]{0,4}正文[ 　]{1,4}.{0,20}$"),

        // Chapter/Section/Part/Episode 序号 标题
        Regex("^[ 　\\t]{0,4}(?:[Cc]hapter|[Ss]ection|[Pp]art|ＰＡＲＴ|[Nn][oO][.、]|[Ee]pisode|(?:内容|文章)?简介|文案|前言|序章|楔子|正文(?!完|结)|终章|后记|尾声|番外)\\s{0,4}\\d{1,4}.{0,30}$"),

        // 特殊符号 序号 标题（【第一章 xxx）
        Regex("(?<=[\\s　])[【〔〖「『〈［\\[](?:第|[Cc]hapter)[\\d零一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]{1,10}[章节].{0,20}$"),

        // 特殊符号 标题（单个，☆★✦✧ 开头）
        Regex("(?<=[\\s　]{0,4})(?:[☆★✦✧].{1,30}|(?:内容|文章)?简介|文案|前言|序章|楔子|正文(?!完|结)|终章|后记|尾声|番外)[ 　]{0,4}$"),

        // 章/卷 序号 标题（卷五 xxx）
        Regex("^[ \\t　]{0,4}(?:(?:内容|文章)?简介|文案|前言|序章|楔子|正文(?!完|结)|终章|后记|尾声|番外|[卷章][\\d零一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]{1,8})[ 　]{0,4}.{0,30}$"),

        // 书名 括号 序号（标题(12)）
        Regex("^[一-龥]{1,20}[ 　\\t]{0,4}[(（][\\d〇零一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]{1,8}[)）][ 　\\t]{0,4}$"),

        // 书名 序号（标题124）
        Regex("^[一-龥]{1,20}[ 　\\t]{0,4}[\\d〇零一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]{1,8}[ 　\\t]{0,4}$"),

        // 字数分割 分节阅读（分节阅读 / 第一页）
        Regex("(?<=[ 　\\t]{0,4})(?:.{0,15}分[页节章段]阅读[-_ ]|第\\s{0,4}[\\d零一二两三四五六七八九十百千万]{1,6}\\s{0,4}[页节]).{0,30}$"),
    )

    /**
     * 判断一行是否为章节标题。
     */
    fun isChapterTitle(line: String): Boolean {
        if (line.isEmpty()) return false
        // 章节标题一般不超过 60 字符
        if (line.length > 60) return false
        return rules.any { it.matches(line) }
    }
}
